import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
const result = await build({ entryPoints: [new URL('./src/client.mjs', import.meta.url).pathname], bundle: true, format: 'cjs', platform: 'browser', target: 'es2022', external: ['react', 'react-dom'], loader: { '.css': 'text' }, write: false, charset: 'utf8' })
await writeFile(new URL('./client.js', import.meta.url), `// Generated by build.mjs.
window.__ModuleLoader__.load({id:'ds-bot-mobile-app',factory:(require)=>{
const module={exports:{}};
${result.outputFiles[0].text}
return Object.defineProperty({...module.exports},Symbol.toStringTag,{value:'Module'});
}});
`)
console.log('Built Mobile App companion')
