import { tr } from "../i18n";
import React, { useRef, useState } from "react";
import { CameraView, useCameraPermissions } from "expo-camera";
import { Button, Label, Notice, Sheet } from "./UI";
export function PairingScanner({
  disabled,
  onScan,
}: {
  disabled: boolean;
  onScan: (value: string) => void;
}) {
  const scanned = useRef(false);
  const [open, setOpen] = useState(false);
  const [error, setError] = useState("");
  const [permission, requestPermission] = useCameraPermissions();
  return (
    <>
      <Button
        secondary
        title={tr("Scan pairing QR code")}
        disabled={disabled}
        onPress={async () => {
          if (permission?.granted || (await requestPermission()).granted) {
            scanned.current = false;
            setOpen(true);
          } else {
            setError(
              "Camera access is needed to scan. You can paste the pairing code instead.",
            );
          }
        }}
      />
      <Notice error text={error} />
      <Sheet
        title={tr("Scan host code")}
        visible={open}
        onClose={() => { scanned.current = true; setOpen(false); }}
      >
        {open && (
          <CameraView
            style={{ height: 350, borderRadius: 20 }}
            barcodeScannerSettings={{ barcodeTypes: ["qr"] }}
            onBarcodeScanned={(result) => {
              if (scanned.current || disabled) return;
              scanned.current = true;
              setOpen(false);
              onScan(result.data);
            }}
          />
        )}
        <Label muted>{tr("Only scan the code generated by your own DSH host.")}</Label>
      </Sheet>
    </>
  );
}
